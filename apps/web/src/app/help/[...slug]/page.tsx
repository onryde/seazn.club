import { notFound, permanentRedirect } from "next/navigation";
import type { Metadata } from "next";
import {
  allHelpArticles, helpArticle, helpNav, helpSectionLabel, renderHelpArticle, staticHelpSlugs,
} from "@/server/help-content";
import { helpRedirectTarget } from "@/server/help-redirects";
import { resolveHelpRelated } from "@/server/help-related";
import { helpBlogLinks } from "@/server/blog-help-links";
import { loadPricingMatrix } from "@/lib/pricing-matrix-server";
import { CompetitionProse } from "@/components/public-site/competition-prose";
import { readingSerif } from "@/components/reading/reading-serif";
import { READING_TITLE } from "@/components/reading/reading-title";
import { HelpBreadcrumb, HelpShell } from "@/components/help/help-shell";
import { HelpRelated } from "@/components/help/help-related";
import { JsonLd } from "@/components/seo/json-ld";
import { helpArticleLd, helpBreadcrumbLd } from "@/lib/help-seo";

// Prerendered and cached at the edge (layout.tsx): a request-time read fails the build. 300 s, because an article with a
// plan token reads the plan table, so a changed fee shows within about ten minutes (five here, five at the edge).
// `revalidate` is per route, so a plain article shares it.
export const dynamic = "error";
export const revalidate = 300;

type Props = { params: Promise<{ slug: string[] }> };

export function generateStaticParams(): { slug: string[] }[] {
  // An article with a plan token needs the plan table, which `next build` cannot read
  // (no database), so it is not prerendered: it renders on its first request and is then
  // cached and regenerated by `revalidate` above. See renderHelpArticle.
  return staticHelpSlugs(allHelpArticles().values()).map((slug) => ({ slug: slug.split("/") }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const article = helpArticle(slug.join("/"));
  if (!article) return {};
  return { title: article.title, description: article.description, alternates: { canonical: `/help/${article.slug}` } };
}

export default async function HelpArticlePage({ params }: Props) {
  const { slug } = await params;
  const article = helpArticle(slug.join("/"));
  if (!article) {
    // A page that moved: answer its old address with a permanent redirect (help-redirects.ts).
    // Served on demand — a source is not in generateStaticParams, and dynamicParams stays on.
    const moved = helpRedirectTarget(slug.join("/"));
    if (moved) permanentRedirect(`/help/${moved}`);
    notFound();
  }

  const href = `/help/${article.slug}`;
  const { html } = await renderHelpArticle(article, loadPricingMatrix);
  const trail = [{ href: `/help#${article.section}`, label: helpSectionLabel(article.section) }];

  // Previous/next within the section, in the help home's own order.
  const pages = (helpNav().find((s) => s.section === article.section)?.articles ?? []).map((a) => ({ href: `/help/${a.slug}`, title: a.title }));
  const i = pages.findIndex((p) => p.href === href);
  const prev = i > 0 ? pages[i - 1]! : null;
  const next = i >= 0 ? (pages[i + 1] ?? null) : null;

  // Throws on a slug that is not an article or a redirect source (help-related.ts): never a dead card.
  const related = resolveHelpRelated(article, allHelpArticles()).map((a) => ({
    href: `/help/${a.slug}`,
    title: a.title,
    section: helpSectionLabel(a.section),
  }));

  // The posts that name this page (blog front-matter `help:`), beside Related and never through it.
  const blogLinks = await helpBlogLinks(article.slug);

  // The page reads like a blog post: its reading style (owner pick "H1", 2026-11-26: the large title and a serif body,
  // components/reading/ and globals.css `.reading-prose`) in its one centred column, which HelpShell draws.
  return (
    <HelpShell>
      <JsonLd data={helpArticleLd({ path: href, name: article.title, description: article.description })} />
      <JsonLd data={helpBreadcrumbLd(trail, { path: href, name: article.title })} />
      <article className={readingSerif.variable}>
        <header>
          <HelpBreadcrumb trail={trail} />
          <h1 className={`mt-3 ${READING_TITLE}`}>{article.title}</h1>
          {article.description ? (
            <p className="mt-3 text-lg leading-relaxed text-slate-600">{article.description}</p>
          ) : null}
        </header>
        <div className="mt-8 min-w-0">
          <CompetitionProse html={html} className="help-prose reading-prose" />
        </div>
        <HelpRelated related={related} prev={prev} next={next} blogLinks={blogLinks} className="min-w-0" />
      </article>
    </HelpShell>
  );
}
