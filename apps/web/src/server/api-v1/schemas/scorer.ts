import { z } from "zod";
import { Uuid, CourtId, VenueId, DivisionStatus } from "./common.ts";
import { SlotLabelRef } from "./scoring.ts";

// ---------------------------------------------------------------------------
// Scorer console (doc 13, PROMPT-18)
