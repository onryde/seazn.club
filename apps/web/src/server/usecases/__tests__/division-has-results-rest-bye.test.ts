// #850 review, finding 2 — `division_has_results()` (V417) must not count a
// round-robin REST BYE as a recorded result.
//
// Since #850 an odd league persists one settled bye row per round at
// GENERATION (`forfeited`, one seat, `{kind:"award", winner}`). V355 matched it
// on `status = 'forfeited'`, so a freshly generated 5-entrant league — nothing
// played — could not be deleted and still held a paid slot once archived,
// while a 4-entrant league beside it deleted cleanly.
//
// Driven through the REAL producer (createEntrants → createStages →
// generateStageFixtures) and the REAL consumers (deleteDivision,
// archiveDivision, divisionConsumesSlotOnArchive, the quota count in
// createDivision). The SQL function's literal stage kinds are pinned to the
// TypeScript authority (`REST_BYE_STAGE_KINDS`) over every engine stage kind,
// both directions, at the bottom.
