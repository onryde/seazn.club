"""BUILD model acceptance tests.

The board under test is the production shape that motivated the whole
investigation (37 fixtures, 5 courts, 26 days x 5 courts x 64 ticks) and it is
generated by `placement_bench_boards.production_board()` — the SAME generator the
bench sweep drives, deliberately shared rather than copied, so the two cannot
drift apart (see the prompt's Step 2b).

These exercise the real solver end to end. Nothing here is mocked: a green run
means CP-SAT actually proved optimality on the real board inside the budget.

--- round 6: identity is POSITIONAL, `bench/` is not ------------------------

`bench/placement_bench_boards.py` is out of scope for round 6 and still returns
string-keyed boards (fixture ids, court names, division/entrant ids) — see
`placement.model`'s module docstring. `_board_positional.to_positional` is the
one place that bridges the two: every board below is converted immediately
after generation, so `build_model` only ever sees the positional shape a real
caller would send after this round.
"""

import os

import pytest
from ortools.sat.python import cp_model

from _board_positional import to_positional
from placement.model import MIN_MS, build_model, solve

#: The production budget from the design spec, and the wall the acceptance
#: criterion is stated at.
PRODUCTION_WALL_SECONDS = 8.0


def _load():
    """One-minute load average, for failure messages only.

    Every wall-clock claim in this service is load-sensitive — the same board
    measures ~4 940 ms/OPTIMAL on an idle box and 8 044 ms/FEASIBLE at load 11
    — so a red that does not say how busy the machine was cannot be triaged.
    Reported, never branched on: a test that skips itself under load is a test
    that never runs in CI.
    """
    return os.getloadavg()[0]


def _production_board():
    # Module name follows the file the prompt's Step 2b names
    # (bench/placement_bench_boards.py) and its siblings placement_bench.py /
    # placement_repair_bench.py. bench/ reaches sys.path via `pythonpath` in
    # pyproject.toml — it is a script directory, not an installed package.
    from placement_bench_boards import production_board

    return to_positional(production_board())


def test_production_board_meets_the_stated_acceptance_criterion():
    """Prompt 02's acceptance criterion, asserted as written, for the first time.

    *"the production board solves to OPTIMAL with 35-37 assignments in under 8
    seconds, verified by an automated test."* Both halves existed in the suite;
    neither was asserted against the other. `test_production_board_solves_under_budget`
    accepts FEASIBLE and `tiers_completed >= 1` at the 8 s wall, and the OPTIMAL
    half is proved in `test_objective.py` at a THIRTY second wall. Measured at
    8 s under load 11: `FEASIBLE, 37 placed, tiers=2, elapsed_ms=8044` — the
    criterion not met, the suite green.

    Note what OPTIMAL means for this chain and why the count is asserted beside
    it: `status` is OPTIMAL only when every requested tier was PROVED, so it
    carries the four-tier claim; and a model with no objective at all also
    returns OPTIMAL, with ZERO placed, so status alone is vacuous. Both
    assertions are load-bearing.

    THIS TEST IS LOAD-SENSITIVE ON PURPOSE. The same board measures ~4 940 ms
    OPTIMAL idle and 8 044 ms FEASIBLE at load 11, on eight search workers over
    six physical cores. That is the acceptance criterion being genuinely
    marginal on a contended box, not a defect in the tier code, and weakening
    the assertion would hide the one thing this test exists to say. The load
    average is reported in the failure message so a red can be triaged rather
    than guessed at; re-run alone before calling it a regression.
    """
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = _production_board()
    model = build_model(fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps)
    load = _load()
    outcome = solve(model, wall_seconds=PRODUCTION_WALL_SECONDS)
    detail = (
        f"status={outcome.status} placed={len(outcome.assignments)} "
        f"tiers_completed={outcome.tiers_completed} elapsed_ms={outcome.elapsed_ms} "
        f"wall={PRODUCTION_WALL_SECONDS}s load1={load:.2f}"
    )
    assert 35 <= len(outcome.assignments) <= 37, detail
    assert outcome.status == "OPTIMAL", detail


def test_production_board_solves_under_budget():
    """The board solves, completely, inside the production wall.

    Renamed from `..._solves_optimal_under_budget`, and the `status ==
    "OPTIMAL"` assertion is gone, because `solve()` no longer answers the
    question that assertion was asking. It was written when `solve()` was T0
    alone (~100 ms, always proved); it now drives the whole T0->T3 chain, whose
    final status reports whether all FOUR tiers were proved inside 8 s. That is
    a claim about the machine as much as the board — measured at 4 940 ms idle
    and past the wall under concurrent load — so it belongs in
    `test_objective.py`, which owns it and runs it deterministically.

    What is asserted here is what this test was always really about, and it is
    the assertion that carries the weight anyway: the board comes back whole.
    A missing objective returns OPTIMAL with ZERO placed, so the count is what
    catches that mutant, never the status.

    The 8 s wall here is inherited, not justified. An earlier version of this
    docstring claimed cutting it to 3 s let the participant-rest and court-gap
    mutants survive; that came from a single run per cell and does not
    reproduce — at six runs both mutants die MORE reliably at 3 s than at 8 s.
    The measured table is in
    `test_assignments_satisfy_every_stated_constraint`, and those two families
    are now guarded properly by `test_participant_rest_is_binding` and
    `test_the_court_turnaround_gap_is_binding`, on contended boards that do not
    depend on the wall at all.
    """
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = _production_board()
    model = build_model(fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps)
    outcome = solve(model, wall_seconds=8.0)
    assert outcome.status in ("OPTIMAL", "FEASIBLE")
    assert 35 <= len(outcome.assignments) <= 37
    assert outcome.tiers_completed >= 1
    assert outcome.elapsed_ms <= 8250


def test_no_court_double_booking():
    # The 8 s wall carries no coverage claim — an earlier comment here said it
    # did, on the strength of one run per cell, and six runs reversed the
    # result. See the measured table in
    # `test_assignments_satisfy_every_stated_constraint`. The court-gap family
    # is guarded by `test_the_court_turnaround_gap_is_binding`, not here.
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = _production_board()
    model = build_model(fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps)
    outcome = solve(model, wall_seconds=8.0)
    assert outcome.assignments, "nothing placed — the loop below would be vacuous"
    seen = {}
    for fixture_index, court_index, start_ms in outcome.assignments:
        key = (court_index, start_ms)
        assert key not in seen, f"double-booked {key}"
        seen[key] = fixture_index


def test_assignments_satisfy_every_stated_constraint():
    """Re-verify the solver's answer against each constraint family, in plain
    Python, the way `validateAssignments` does on the TS side.

    The two tests above leave most of the model untestable: deleting the
    participant-rest `AddNoOverlap`, the order-dependency inequality or the
    per-division day cap leaves both of them green (measured — the rest mutant
    survived them). A solver whose constraint families can be removed without
    a test noticing is the failure mode this repo has been bitten by before,
    so each family gets an assertion that fails without it.

    DO NOT TREAT THIS TEST AS THE GUARD FOR COURT GAP OR PARTICIPANT REST.
    It catches them only by luck. Measured over six runs per cell against a
    pristine mirror, with the mutation's presence verified in each run:

        mutant                                   8 s wall     3 s wall
        M2  participant-rest NoOverlap deleted   RED 5/6      RED 6/6
        M7  gap dropped from the court width     RED 1/6      RED 6/6
        baseline (unmutated)                     GREEN 2/2    GREEN 2/2

    Two things follow, and the second corrects a claim an earlier version of
    this docstring asserted as fact:

      * M7 is a **coin flip here — 1 in 6** at the shipped wall. It is now
        genuinely guarded by `test_the_court_turnaround_gap_is_binding`, and
        M2 by `test_participant_rest_is_binding`, both on purpose-built
        contended boards that decide on a proved COUNT in milliseconds.
      * A LONGER WALL MAKES THESE TWO **LESS** DETECTABLE, NOT MORE. The
        earlier claim that "T1's packing pressure is what exposes them" was
        drawn from a single run per cell and is wrong — with six runs the
        effect reverses. The real driver is that this board is uncontended:
        8 320 slots, 37 fixtures and a day cap of one per division per day
        leave everything naturally spread out, so a deleted turnaround or rest
        window usually changes no placement at all. The more tiers finish, the
        better-optimised the board, and the fewer incidental violations remain
        for this test to trip over.

    So the 8 s wall is NOT load-bearing coverage. It is kept only because it
    is what the other assertions here were measured at and nothing argues for
    changing it; if suite runtime ever needs to come down this is a legitimate
    place to take it from, provided the M1-M8 matrix is re-run to confirm the
    families it really does guard (M1, M3, M4, M5, M8) still die.
    """
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = _production_board()
    model = build_model(fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps)
    outcome = solve(model, wall_seconds=8.0)
    assert outcome.assignments, "nothing placed — the rest of this test would be vacuous"
    assert len(outcome.assignments) == len(fixtures), (
        "not every fixture was placed, so some constraint arm below may be vacuous"
    )

    dur_ms = constraints["match_minutes"] * MIN_MS
    gap_ms = constraints["gap_minutes"] * MIN_MS
    rest_by_division = constraints["rest_by_division"]
    day_cap_by_division = constraints["day_cap_by_division"]

    # Fixture identity is now POSITION, so these are lists, not id-keyed dicts.
    entrants_of = [ents for ents, _div in fixtures]
    division_of = [div for _ents, div in fixtures]
    placed = {fi: (court, start) for fi, court, start in outcome.assignments}
    legal_court_starts = {(court, start) for court, start, _day in grid_slots}

    # every placement lands on a tick THAT COURT actually offers
    for fi, (court, start) in placed.items():
        assert 0 <= court < num_courts, f"fixture {fi} placed on unknown court {court}"
        assert (court, start) in legal_court_starts, (
            f"fixture {fi} placed at {start} on court {court}, not a legal slot"
        )

    # court turnaround (match+gap), movable vs movable AND vs immovable rows
    occupancy = [(court, start, fi) for fi, (court, start) in placed.items()]
    occupancy += [(court, start, f"existing:{k}") for k, (court, start) in enumerate(existing)]
    for a in range(len(occupancy)):
        for b in range(a + 1, len(occupancy)):
            court_a, start_a, name_a = occupancy[a]
            court_b, start_b, name_b = occupancy[b]
            if court_a != court_b:
                continue
            assert abs(start_a - start_b) >= dur_ms + gap_ms, (
                f"court turnaround violated on court {court_a}: {name_a}@{start_a} vs {name_b}@{start_b}"
            )

    # participant rest: an entrant's two matches are separated by match+rest
    by_entrant = {}
    for fi, (_court, start) in placed.items():
        for entrant in entrants_of[fi]:
            by_entrant.setdefault(entrant, []).append((start, fi))
    for entrant, rows in by_entrant.items():
        rows.sort()
        for a in range(len(rows)):
            for b in range(a + 1, len(rows)):
                (start_a, fi_a), (start_b, fi_b) = rows[a], rows[b]
                need = dur_ms + rest_by_division.get(division_of[fi_a], 0) * MIN_MS
                assert start_b - start_a >= need, (
                    f"rest violated for entrant {entrant}: fixture {fi_a}@{start_a} vs "
                    f"fixture {fi_b}@{start_b}, need {need}ms"
                )

    # order dependencies: `after` starts no earlier than `before` + match + its own rest
    checked_deps = 0
    for before_i, after_i in deps:
        if before_i not in placed or after_i not in placed:
            continue
        need = dur_ms + rest_by_division.get(division_of[after_i], 0) * MIN_MS
        assert placed[after_i][1] >= placed[before_i][1] + need, (
            f"dependency violated: fixture {after_i} must start >= fixture {before_i} + {need}ms"
        )
        checked_deps += 1
    assert checked_deps == len(deps), "a dependency pair went unplaced — that arm would be vacuous"

    # per-division day cap. Bucketed by the board's own `day_index`, not by
    # re-deriving `start // DAY_MS` — the model groups by the caller's day and
    # re-deriving here would let a wrong day_index satisfy both sides at once.
    day_of_start = {start: day for _court, start, day in grid_slots}
    per_division_day = {}
    for fi, (_court, start) in placed.items():
        key = (division_of[fi], day_of_start[start])
        per_division_day[key] = per_division_day.get(key, 0) + 1
    for (division, day), count in per_division_day.items():
        assert count <= day_cap_by_division[division], (
            f"day cap violated: division {division} day {day} has {count} > "
            f"{day_cap_by_division[division]}"
        )


# --- pinned/immovable rows, on a board where they actually contend ----------


def test_pinned_rows_are_not_overwritten_when_a_fixture_wants_the_slot():
    """The `existing` constraint family, on the only board that can test it.

    On `production_board()` this family is INERT, not merely unasserted: three
    pins against 8 320 grid slots and 37 movable fixtures means nothing ever
    competes for a pinned (court, tick). Measured, with the pinned-row fold
    deleted from `build_model`: **0 pin-involving violations with the
    constraint and 0 without it**, on both the zero-epoch and the real-epoch
    board. An assertion added to the production board therefore cannot catch
    the deletion — the corpus is blind, and no amount of asserting fixes a
    corpus.

    `pin_contended_board()` fixes the corpus instead. Five of its six
    (court, tick) pairs are pinned and three movable fixtures compete for the
    sixth, so the constraint is the ONLY thing keeping them off an occupied
    court. With it: one placement. Without it: three, two of them on top of a
    match already being played, reported OPTIMAL with `error` unset.
    """
    from placement_bench_boards import PIN_BOARD_FIXTURES, PIN_BOARD_FREE_SLOTS, pin_contended_board

    board = to_positional(pin_contended_board())
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = board

    # The board genuinely contends — otherwise everything below is vacuous.
    assert PIN_BOARD_FIXTURES > PIN_BOARD_FREE_SLOTS
    assert len(fixtures) == PIN_BOARD_FIXTURES
    assert len(existing) == len(grid_slots) - PIN_BOARD_FREE_SLOTS
    assert not constraints["day_cap_by_division"], "a day cap would confound the pinned-row family"
    assert set(constraints["rest_by_division"].values()) == {0}, "rest would confound the pinned-row family"

    model = build_model(*board)
    outcome = solve(model, wall_seconds=5.0)
    detail = f"status={outcome.status} tiers={outcome.tiers_completed} board={sorted(outcome.assignments)}"

    assert outcome.tiers_completed == 4, detail  # tiny board; anything less means it did not run
    assert len(outcome.assignments) == PIN_BOARD_FREE_SLOTS, (
        "a movable fixture was placed into a pinned slot — the pinned-row fold in build_model "
        f"is not binding. {detail}"
    )

    pinned = set(existing)  # (court_index, start) -- PinnedRow carries no identity of its own
    for _fi, court, start in outcome.assignments:
        assert (court, start) not in pinned, f"fixture placed on top of an immovable row at {(court, start)}"

    # The one placement is on the one free slot, and it is a real slot.
    free = sorted({(court, start) for court, start, _day in grid_slots} - pinned)
    assert [(court, start) for _fi, court, start in outcome.assignments] == free, detail


def test_the_court_turnaround_gap_is_binding():
    """The court gap, on a board where it actually decides something.

    `gap_minutes` widens every court interval to `match + gap`. On
    `production_board()` that is almost never observable: 8 320 slots, 37
    fixtures and a day cap of one per division per day mean nothing is forced
    onto the same court close together, so narrowing the interval usually
    changes no placement. Measured over six runs at the production 8 s wall,
    the mutant that drops `gap_ms` from the width was caught **2 times in 6** —
    a coin flip, not a guard, and one that reads as a regression in CI.

    Here the gap is the only thing deciding how many fixtures fit:

        width = match + gap  ->  GAP_PROBE_CAPACITY            placements
        width = match alone  ->  GAP_PROBE_CAPACITY_WITHOUT_GAP placements

    T0 settles that in milliseconds and the answer does not depend on the
    wall, on how many tiers completed, or on the day cap.

    Run as a T0-ONLY chain (`tiers=(TIER_PLACED,)`, the prefix the bench also
    uses) rather than through `solve()`. That is not a shortcut, it is the
    question: "how many fit" is exactly what T0 proves, and `tiers_completed
    == 1` here means CP-SAT proved no board places more. Measured, the full
    chain on this board burns a 5 s wall and still returns `tiers_completed=1`
    — fourteen interchangeable fixtures over thirteen ticks is a symmetric
    packing problem and T1 cannot close its bound — so asserting the whole
    ladder here would have made a T0 fact hostage to a T1 proof that never
    lands.
    """
    from placement.objective import TIER_PLACED, run_tier_chain
    from placement_bench_boards import (
        GAP_PROBE_CAPACITY,
        GAP_PROBE_CAPACITY_WITHOUT_GAP,
        GAP_PROBE_FIXTURES,
        gap_contended_board,
    )

    board = to_positional(gap_contended_board())
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = board

    # The board must genuinely contend, or every assertion below is vacuous.
    assert GAP_PROBE_CAPACITY < GAP_PROBE_CAPACITY_WITHOUT_GAP <= GAP_PROBE_FIXTURES
    assert len(fixtures) == GAP_PROBE_FIXTURES
    assert not existing and not deps, "pins or dependencies would confound the gap family"
    assert not constraints["day_cap_by_division"], "a day cap would confound the gap family"
    assert set(constraints["rest_by_division"].values()) == {0}, "rest would confound the gap family"

    model = build_model(*board)
    outcome = run_tier_chain(model, model.fixture_vars, wall_seconds=5.0, tiers=(TIER_PLACED,))
    detail = f"status={outcome.status} tiers={outcome.tiers_completed} board={sorted(outcome.assignments)}"

    # T0 PROVED its maximum — without this the count below could be a board the
    # clock cut short rather than the most that fits.
    assert outcome.tiers_completed == 1, detail
    assert outcome.status == "OPTIMAL", detail

    assert dict(outcome.objective_values)[TIER_PLACED] == GAP_PROBE_CAPACITY, (
        f"expected {GAP_PROBE_CAPACITY} placements; {GAP_PROBE_CAPACITY_WITHOUT_GAP} means the court "
        f"interval lost its turnaround gap. {detail}"
    )
    assert len(outcome.assignments) == GAP_PROBE_CAPACITY, detail

    # ...and say it directly, not only as a count.
    need = (constraints["match_minutes"] + constraints["gap_minutes"]) * MIN_MS
    placed = sorted((court, start) for _fi, court, start in outcome.assignments)
    for a in range(len(placed)):
        for b in range(a + 1, len(placed)):
            if placed[a][0] == placed[b][0]:
                assert abs(placed[a][1] - placed[b][1]) >= need, (
                    f"court turnaround violated on court {placed[a][0]}: {placed[a][1]} vs "
                    f"{placed[b][1]}, need {need}ms"
                )


def test_participant_rest_is_binding():
    """Participant rest, on a board where it actually decides something.

    Seven fixtures share one entrant across seven courts, so court exclusivity
    cannot bind and the per-entrant rest window is the only thing spacing them:

        rest enforced   ->  REST_PROBE_CAPACITY placements
        rest removed    ->  REST_PROBE_FIXTURES placements

    On `production_board()` the same mutant is caught only most of the time —
    re-measured over six runs, RED 5 of 6 at the production 8 s wall and 6 of 6
    at a 3 s wall. One miss in six is a flake that reads as a regression, and
    note the direction: the SHORTER wall was the more reliable killer, so this
    was never something a longer solve could fix.

    Kills both the "rest `AddNoOverlap` deleted" mutant and the "rest_ms
    zeroed" one, since either lets all seven seat.
    """
    from placement.objective import TIER_PLACED, run_tier_chain
    from placement_bench_boards import REST_PROBE_CAPACITY, REST_PROBE_FIXTURES, rest_contended_board

    board = to_positional(rest_contended_board())
    fixtures, num_courts, grid_slots, step_minutes, constraints, existing, deps = board

    assert REST_PROBE_CAPACITY < REST_PROBE_FIXTURES == len(fixtures)
    assert num_courts >= REST_PROBE_FIXTURES, "court exclusivity must not be able to bind"
    assert not existing and not deps and not constraints["day_cap_by_division"]
    shared = set.intersection(*(set(entrants) for entrants, _div in fixtures))
    assert len(shared) == 1, "every fixture must share exactly one entrant for rest to be the variable"
    (shared_entrant,) = shared

    model = build_model(*board)
    outcome = run_tier_chain(model, model.fixture_vars, wall_seconds=5.0, tiers=(TIER_PLACED,))
    detail = f"status={outcome.status} tiers={outcome.tiers_completed} board={sorted(outcome.assignments)}"

    assert outcome.tiers_completed == 1, detail
    assert outcome.status == "OPTIMAL", detail
    assert dict(outcome.objective_values)[TIER_PLACED] == REST_PROBE_CAPACITY, (
        f"expected {REST_PROBE_CAPACITY} placements; {REST_PROBE_FIXTURES} means the participant-rest "
        f"window is not binding. {detail}"
    )

    # ...and directly: the shared entrant's matches are match+rest apart.
    only_division = next(iter(constraints["rest_by_division"]))
    need = (constraints["match_minutes"] + constraints["rest_by_division"][only_division]) * MIN_MS
    starts = sorted(start for _fi, _court, start in outcome.assignments)
    for earlier, later in zip(starts, starts[1:]):
        assert later - earlier >= need, (
            f"rest violated for entrant {shared_entrant}: {earlier} vs {later}, need {need}ms"
        )


# --- an unplaceable board must not report a NEGATIVE makespan ---------------


def test_an_empty_board_reports_a_non_negative_makespan():
    """`mk_hi - mk_lo` is unpinned when nothing is placed, and T1 MINIMISES it.

    Both squeeze constraints are `OnlyEnforceIf(placed[i])`, so with an empty
    board `mk_lo` and `mk_hi` float freely over `[0, max_end]` and minimising
    their difference drives `mk_hi` to 0 and `mk_lo` to `max_end`. The chain
    then proves that optimal and publishes it. Measured 6/6, one fixture made
    unplaceable by a self-dependency:

        OPTIMAL, placed=0, error unset,
        objective_values=[('placed', 0), ('makespan', -1767258600000), ...]

    A negative epoch-shaped number on the wire, presented as a proved optimum.
    `build.ts` compares tier values against its own board metrics, and no
    caller has any reason to defend against a negative duration.

    Fixed in the model rather than at the ACL: a duration cannot be negative is
    an invariant of the term, so every consumer — the bench, the tier chain,
    the wire — gets the same answer. An empty board has a makespan of zero.

    Self-dependency is DELIBERATELY still accepted (an unplaceable fixture
    shows up as a lower `placed`, which is visible); it is only the negative
    number that had to go.
    """
    num_courts = 1
    grid_slots = [(0, _STRADDLE_A, 0), (0, _STRADDLE_A + 40 * MIN_MS, 0)]
    fixtures = [([0, 1], 0)]
    constraints = {
        "match_minutes": 30,
        "gap_minutes": 10,
        "rest_by_division": {0: 0},
        "day_cap_by_division": {},
    }
    # A self-dependency (fixture 0 depends on itself) makes it unplaceable.
    model = build_model(fixtures, num_courts, grid_slots, 40, constraints, [], [(0, 0)])
    outcome = solve(model, wall_seconds=5.0)

    assert outcome.assignments == [], "the self-dependency should make fixture 0 unplaceable"
    reported = dict(outcome.objective_values)
    assert reported["placed"] == 0
    assert reported["makespan"] >= 0, (
        f"a negative duration reached the objective values: {outcome.objective_values}"
    )
    assert reported["makespan"] == 0, (
        f"an empty board has no makespan at all, got {reported['makespan']}"
    )


def test_a_placed_board_still_reports_its_real_makespan():
    """The clamp must not have flattened the term. Two fixtures forced onto two
    different ticks by a single court give a makespan of exactly one tick gap
    plus one match."""
    num_courts = 1
    step = 40 * MIN_MS
    grid_slots = [(0, _STRADDLE_A + k * step, 0) for k in range(2)]
    fixtures = [([0, 1], 0), ([2, 3], 0)]
    constraints = {
        "match_minutes": 30,
        "gap_minutes": 10,
        "rest_by_division": {0: 0},
        "day_cap_by_division": {},
    }
    model = build_model(fixtures, num_courts, grid_slots, 40, constraints, [], [])
    outcome = solve(model, wall_seconds=5.0)

    assert len(outcome.assignments) == 2
    assert dict(outcome.objective_values)["makespan"] == step + 30 * MIN_MS


# --- the day cap binds on the CALLER's day, not on a UTC boundary -----------

#: A UTC-midnight-straddling session, in `build_model`'s parameter shape.
#:
#: 2026-01-01T23:00:00Z and 2026-01-02T01:00:00Z. For an org two hours ahead of
#: UTC those are 01:00 and 03:00 on the SAME local morning — one session day,
#: and one day-cap bucket. `start_ms // DAY_MS` puts them in two.
_STRADDLE_A = 1_767_308_400_000  # 2026-01-01T23:00:00Z
_STRADDLE_B = 1_767_315_600_000  # 2026-01-02T01:00:00Z


def _straddling_board(day_index_of):
    """Two ticks either side of UTC midnight, two courts, two `d1`-equivalent
    (division 0) fixtures capped at one per day. Court capacity cannot bind
    (two courts, two ticks, two fixtures) and entrants are disjoint, so the
    day cap is the only thing deciding how many are placed — a COUNT that T0
    proves in milliseconds, independent of the wall and of which tiers ran.
    """
    num_courts = 2
    grid_slots = [
        (c, start, day_index_of(start)) for c in (0, 1) for start in (_STRADDLE_A, _STRADDLE_B)
    ]
    fixtures = [([0, 1], 0), ([2, 3], 0)]
    constraints = {
        "match_minutes": 30,
        "gap_minutes": 0,
        "rest_by_division": {0: 0},
        "day_cap_by_division": {0: 1},
    }
    return fixtures, num_courts, grid_slots, 60, constraints, [], []


def test_the_day_cap_groups_by_the_callers_day_index_not_by_utc():
    """One local day is one cap bucket, whatever UTC thinks.

    `start_ms // DAY_MS` is a UTC day. The deploy region is `lhr` and
    Europe/London is UTC+1 for about seven months of the year, and orgs further
    out are worse: for UTC+10, a 09:00 local match and a 19:00 local match on
    the same day land in DIFFERENT UTC buckets, so a cap of one per day admits
    two. Same class as this repo's `settings.tz`-vs-`settings.orgTz` bug.

    The solver stays timezone-agnostic by design (timezones-as-policy are
    outside this bounded context): the caller, which already knows the org's
    zone, resolves each slot to its local calendar day and sends the integer.

    Both ticks carry `day_index = 0`, so the cap admits exactly ONE. Deriving
    the day from the timestamp instead admits TWO, and reports it OPTIMAL.
    """
    board = _straddling_board(lambda _start: 0)
    model = build_model(*board)
    outcome = solve(model, wall_seconds=3.0)

    assert outcome.tiers_completed >= 1, "T0 itself did not complete — the count below is vacuous"
    assert len(outcome.assignments) == 1, (
        f"expected the cap to admit one fixture on the single local day, got "
        f"{outcome.assignments}"
    )


def test_two_day_indices_over_one_utc_day_give_two_buckets():
    """The converse, so the test above cannot pass by the cap simply being
    stricter. Same two ticks, same cap — but the caller calls them two days, so
    two fixtures fit. Without both halves, `on_day[i][d] = 0` for every d would
    satisfy the first assertion and nothing would notice.
    """
    board = _straddling_board(lambda start: 0 if start == _STRADDLE_A else 1)
    grid_slots = board[2]
    day_of_start = {start: day for _court, start, day in grid_slots}
    model = build_model(*board)
    outcome = solve(model, wall_seconds=3.0)

    assert outcome.tiers_completed >= 1
    assert len(outcome.assignments) == 2, (
        f"two declared days must give two cap buckets, got {outcome.assignments}"
    )
    # And they must land on ONE DAY EACH, not merely number two. The count
    # alone cannot see a fixture claiming a day it is not on: total capacity is
    # `days * cap` however the claims are distributed, so dropping the upper
    # range bound leaves the count at 2 while both fixtures sit on the day-1
    # tick and one of them books day 0's allowance. T1 actively drives that —
    # a shorter makespan wants both on the same tick.
    assert sorted(day_of_start[start] for _fi, _court, start in outcome.assignments) == [0, 1], (
        f"the cap of one per day was satisfied by a day CLAIM, not by a placement: "
        f"{[(fi, day_of_start[start]) for fi, _court, start in outcome.assignments]}"
    )


