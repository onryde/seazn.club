-- V469 — the email outbox (phase 1): one durable row per transactional email, written on the caller's own
-- transaction, sent after commit and retried by a worker. Spec: docs/superpowers/specs/2026-10-19-email-outbox-design.md.
--
-- WHY. Today a sign-in link or a chess invite is mailed inline, and a failed or lost send is invisible: the player
-- never gets the link and nobody can see that. The outbox makes "we meant to send this" a row that survives a crash
-- and a Resend outage, and carries the provider's later verdict (delivered, bounced, ...) back onto the same row.
--
-- WHAT IT REPLACES. `email_queue` (created by v1-baseline/V028 and again by deltas/V104) is dropped here. Nothing
-- reads or writes it: `git grep -n email_queue` finds only those two migrations. A greenfield-schema stance, so no
-- data is carried over.
--
-- THE BODY IS A LIVE CREDENTIAL. A sign-in link and a match-room link both work as bearer tokens, so `body_sealed`
-- holds the rendered email only as an envelope sealed by the outbox's own key (EMAIL_OUTBOX_KEK), and only
-- while the row can still be retried (queued, sending). Every other status must have no body: the CHECK is the
-- database's own refusal to keep a credential once a row is finished, whatever the application forgets to null.
-- `meta` is the non-secret companion (ids, stamps) a kind's hooks read; it never carries a token.
--
-- INSERT-ONLY FOR THE TENANT. `app_user` gets INSERT and nothing else (no SELECT, UPDATE or DELETE), so a caller inside
-- `withTenant` can enqueue on its own transaction yet can never read another recipient's credential back. The id is
-- generated by the caller and the insert uses no RETURNING (RETURNING needs SELECT). The dispatcher, the worker, the
-- webhook and the status read all run as the privileged role. The policy scopes the insert to the caller's org, so an
-- org-less row (the sign-in link has no org) can only be written by the privileged role.
--
-- REPLACE ON INSERT. A new row for the same kind + ref + recipient (case-insensitive) in the same organisation
-- supersedes every older non-terminal row: the sign-in link, because a newer link deletes the older unused one so
-- retrying the older row would mail a dead link; the chess invite, because the older room token still works and
-- retrying it would mail the player a second invite. The supersede is a trigger so no writer can forget it, and it
-- is SECURITY DEFINER with a pinned search_path (the V451 shape) because the tenant caller holds no UPDATE.
-- Because it runs as the definer it bypasses RLS, so it must fence tenants itself: it matches `org_id` too
-- (`is not distinct from`, so two org-less sign-in links still replace each other). Without that fence an
-- app_user in one org could supersede, and null the body of, another org's pending row by naming its ref and
-- recipient.
create table email_outbox (
  -- Client-generated. Also the idempotency key sent to the provider, so a retry of the same row can never mail twice.
  id              uuid primary key,
  kind            text not null,
  -- What the email is about: for a chess invite, the board and seat. Free text, scoped by kind.
  ref_type        text not null,
  ref_id          text not null,
  -- Nullable: the sign-in link belongs to no organisation. A deleted org takes its rows with it.
  org_id          uuid references organizations(id) on delete cascade,
  -- Non-secret data a kind's hooks need after the send (e.g. the seat stamp). Never a token, never a body.
  meta            jsonb not null default '{}'::jsonb,
  recipient       text not null,
  subject         text not null,
  -- The sealed html + text envelope. Present only while status is queued or sending (a CHECK below). Deliberately NOT
  -- required there: where no KEK is configured AND no Resend key is (local dev, CI), the sender writes a queued row
  -- with no body and the attempt ends it `dead` ('no_api_key'); a body that is missing while a key IS set ends it
  -- `dead` ('body_missing'). A "must hold a body" CHECK would refuse those rows at enqueue and fail the caller's
  -- transaction in exactly the environments that cannot send.
  body_sealed     bytea,
  -- Transactional mail ignores the marketing suppression list; the caller decides, so there is no default.
  transactional   boolean not null,
  status          text not null default 'queued',
  attempts        integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  -- Set exactly while status = 'sending': a crashed attempt's lease lapses and the row becomes due again.
  lease_until     timestamptz,
  -- After this the email is worthless (the link has stopped working); the worker ends the row `expired`, unsent.
  expires_at      timestamptz not null,
  last_error      text,
  -- The provider's message id, once accepted. A webhook finds its row by it.
  provider_id     text,
  created_at      timestamptz not null default now(),
  sent_at         timestamptz,
  status_at       timestamptz not null default now(),

  -- Closed sets. A third kind or a thirteenth status is a code change AND a migration.
  -- outbox-schema.test.ts reads these two back and requires them to equal constants.ts.
  constraint email_outbox_kind_valid check (kind in ('magic_link', 'chess_invite')),
  constraint email_outbox_status_valid check (status in (
    'queued', 'sending', 'sent', 'delayed', 'delivered',
    'bounced', 'complained', 'failed', 'suppressed', 'expired', 'dead', 'replaced'
  )),
  constraint email_outbox_attempts_nonneg check (attempts >= 0),
  constraint email_outbox_ref_type_nonempty check (ref_type <> ''),
  constraint email_outbox_ref_id_nonempty check (ref_id <> ''),
  constraint email_outbox_recipient_nonempty check (recipient <> ''),
  -- The credential never outlives the last retry.
  constraint email_outbox_body_only_while_retryable check (
    body_sealed is null or status in ('queued', 'sending')
  ),
  -- A lease exists exactly while a row is being sent: both directions, so a 'sending' row can always be reclaimed.
  constraint email_outbox_lease_only_while_sending check (
    (status = 'sending') = (lease_until is not null)
  )
);

drop table if exists email_queue;

-- The worker's due scan and its lease reclaim.
create index email_outbox_due_idx on email_outbox (next_attempt_at) where status = 'queued';
create index email_outbox_lease_idx on email_outbox (lease_until) where status = 'sending';
-- A provider event finds its row by the provider's id.
create unique index email_outbox_provider_idx on email_outbox (provider_id) where provider_id is not null;
-- "Every email about this thing", newest first (the arbiter's status read).
create index email_outbox_ref_idx on email_outbox (ref_type, ref_id, created_at desc);
-- The 90-day purge of finished rows.
create index email_outbox_created_idx on email_outbox (created_at);
-- The replace trigger's lookup; its predicate is the trigger's own status list.
create index email_outbox_replace_idx on email_outbox (kind, ref_type, ref_id, lower(recipient))
  where status in ('queued', 'sending', 'sent', 'delayed');

create function email_outbox_replace_older() returns trigger
  language plpgsql security definer
  set search_path = ${flyway:defaultSchema}, pg_temp as $$
begin
  update email_outbox
     set status = 'replaced', body_sealed = null, lease_until = null, status_at = now()
   where kind = new.kind and ref_type = new.ref_type and ref_id = new.ref_id
     and lower(recipient) = lower(new.recipient) and id <> new.id
     and org_id is not distinct from new.org_id
     and status in ('queued', 'sending', 'sent', 'delayed');
  return new;
end $$;
create trigger email_outbox_replace_older before insert on email_outbox
  for each row execute function email_outbox_replace_older();

alter table email_outbox enable row level security;
alter table email_outbox force row level security;
create policy email_outbox_enqueue on email_outbox for insert to app_user
  with check (org_id = current_org_id());
grant insert on email_outbox to app_user;
