-- `swiss_first_round` is the first Swiss round the entrant is in the field for. Null means from round 1, which is every
-- entrant enrolled before Start. A Pair of round r seats only the entrants whose first round is <= r
-- (`swissFieldForRound`, apps/web/src/server/usecases/stages.ts), and the round history credits an implicit bye for round
-- r only to an entrant who was in that round's field. So a latecomer's missed rounds score 0 (FIDE C.04.2 2.4) and do
-- not spend their bye (rulebook P-A4). Task 9's late-entry path is the writer.
--
-- A schema change only. A new nullable column moves no stored value: every existing row reads null (from round 1), which
-- is exactly today's behaviour.
--
-- ─── BACKFILL: OWED ONLY IF PROD'S COUNT 4 > 0 (LOUD) ──────────────────────────────────────────────────────────────────
