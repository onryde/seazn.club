import { describe, expect, it } from "vitest";
import { classifyGenerateRail, generatePathNote, generatePathTotals, parseGeneratePathNote, StageNotGeneratable } from "../lib/generate-path.ts";
import { MixedLedger } from "../lib/driver/mixed.ts";
import { harnessFaults, type JudgedRun } from "../lib/judge.ts";

const seen = (generateOffered: boolean, completeOffered: boolean, fixtureRows: number) => ({ stageId: "s1", generateOffered, completeOffered, fixtureRows });

describe("classifyGenerateRail", () => {
  it("Generate offered is a live click, whatever else shows", () => {
    expect(classifyGenerateRail(seen(true, false, 0))).toBe("live-click");
    expect(classifyGenerateRail(seen(true, true, 3))).toBe("live-click");
  });
  it("no Generate, Complete offered, rows listed is generated by Start", () => {
    expect(classifyGenerateRail(seen(false, true, 1))).toBe("generated-by-start");
  });
  it("every other shape is a named fault", () => {
    for (const [c, r] of [[false, 0], [false, 5], [true, 0]] as const) {
      expect(() => classifyGenerateRail(seen(false, c, r)), `${c}/${r}`).toThrow(StageNotGeneratable);
    }
  });
});

describe("generate path tally", () => {
  it("the note round-trips and the parser refuses anything else", () => {
    expect(parseGeneratePathNote(generatePathNote(2, 5))).toEqual({ live: 2, start: 5 });
    expect(parseGeneratePathNote("generate path: live-click=x generated-by-start=1")).toBeNull();
  });
  it("a ledger files its tally on mixed-driver-coverage, and none when no generate was reported", () => {
    const l = new MixedLedger();
    l.record("start", "browser");
    expect(l.coverage().evidence).toEqual([]);
    l.generatePath("generated-by-start");
    l.generatePath("generated-by-start");
    l.generatePath("live-click");
    expect(l.coverage().evidence).toContain(generatePathNote(1, 2));
    expect(() => l.generatePath("nope" as never)).toThrow(/not a generate path/);
  });
});

describe("run-level anti-vacuity", () => {
  const kase = (id: string, live: number, start: number) => ({
    caseId: id, state: "works", reason: "", planned: undefined, durationMs: 5,
    checks: [{ id: "mixed-driver-coverage", kind: "assertion", verdict: "pass", checked: 1, reason: "", evidence: [generatePathNote(live, start)] }],
  });
  const run = (...cases: ReturnType<typeof kase>[]) => ({ cases }) as unknown as JudgedRun;

  it("totals sum across cases", () => {
    expect(generatePathTotals(run(kase("a", 1, 2), kase("b", 0, 3)).cases)).toEqual({ live: 1, start: 5, cases: 2 });
  });
  it("zero live clicks across a run with Start-drawn steps is a vacuous fault", () => {
    const f = harnessFaults(run(kase("a", 0, 2), kase("b", 0, 1)), { plannedNotRun: "allow" });
    expect(f).toHaveLength(1);
    expect(f[0]).toMatchObject({ caseId: "(run)", kind: "vacuous" });
  });
  it("one live click anywhere in the run clears it; a run that filed no tally is not asked", () => {
    expect(harnessFaults(run(kase("a", 0, 2), kase("b", 1, 0)), { plannedNotRun: "allow" })).toEqual([]);
    expect(harnessFaults(run(), { plannedNotRun: "allow" })).toEqual([]);
  });
});
